-- Payments are recorded per invoice.
-- Every invoice that exists when payments are introduced counts as settled (agreed with the owner);
-- debt that was still open then goes into client.opening_debt by hand.
alter table invoice add column legacy_paid boolean not null default false;
update invoice set legacy_paid = true;

create table payment (
    id          bigint generated by default as identity primary key,
    invoice_id  bigint not null references invoice (id),
    amount      numeric(14, 2) not null check (amount > 0),
    paid_on     date not null,
    method      varchar(20) not null,
    note        varchar(500),
    created_by  varchar(100),
    created_at  timestamp with time zone not null
);
create index idx_payment_invoice on payment (invoice_id);
