-- Variants (colours/shades) of one product: same price, category and pack, different colour.
-- A product without variants is sold as is; a product with variants is sold by variant.
create table product_variant (
    id         bigint generated by default as identity primary key,
    product_id bigint not null references product (id) on delete cascade,
    name       varchar(255) not null,
    -- Own price when this colour costs differently; null = the product price
    price      numeric(14, 2) check (price is null or price >= 0),
    active     boolean not null default true,
    sort_order integer
);
create index idx_variant_product on product_variant (product_id);

-- Which colour an invoice line is for (the line keeps its own name snapshot as before)
alter table invoice_line add column variant_id bigint references product_variant (id) on delete set null;
create index idx_line_variant on invoice_line (variant_id);
